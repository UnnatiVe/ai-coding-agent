export interface PathGuardResult {
  allowed: boolean;
  error?: string;
}

function extractExplicitRequestedPath(prompt: string): string | undefined {
  const createOnlyMatch = prompt.match(
    /\bcreate\s+only\s+(?:`([^`]+)`|"([^"]+)"|'([^']+)'|([a-zA-Z0-9_.-]+(?:[\\/][a-zA-Z0-9_.-]+)*\.[a-zA-Z0-9]+))/i,
  );

  const fallbackMatch = prompt.match(
    /\b(?:create|add|write|generate)\b[\s\S]{0,100}?`([^`]+\.[a-z0-9]+)`/i,
  );

  const match = createOnlyMatch ?? fallbackMatch;

  const requestedPath = match?.[1] ?? match?.[2] ?? match?.[3] ?? match?.[4];

  return requestedPath?.trim().replace(/\\/g, "/");
}

export function checkRequestedPath(
  prompt: string,
  targetPath: string,
): PathGuardResult {
  const requestedPath = extractExplicitRequestedPath(prompt);

  const taskDisallowsOtherExistingFileChanges =
    /\bcreate only\b|\bonly create\b|\bdo not modify\b[\s\S]{0,120}\bexisting files\b|\bonly (?:modify|change|create)\b/i.test(
      prompt,
    );

  const normalizedTargetPath = targetPath.replace(/\\/g, "/");

  if (
    taskDisallowsOtherExistingFileChanges &&
    (!requestedPath || requestedPath !== normalizedTargetPath)
  ) {
    return {
      allowed: false,
      error:
        `The task only permits editing explicitly requested files. ` +
        `You attempted to modify "${normalizedTargetPath}". ` +
        "Do not edit this file. Create or edit only the requested file using the appropriate workspace tool.",
    };
  }

  return { allowed: true };
}